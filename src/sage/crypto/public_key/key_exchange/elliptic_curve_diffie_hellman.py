r"""
Elliptic Curve Diffie-Hellman

Toy implementation of the elliptic curve Diffie-Hellman (ECDH) key exchange
over an elliptic curve defined over a finite field.

Alice and Bob publicly agree on an elliptic curve `E` over a finite field
and on a base point `G` of `E` of order `n`. Alice chooses a secret integer
`d_A` and sends the point `Q_A = d_A G` to Bob. Likewise, Bob chooses a
secret integer `d_B` and sends the point `Q_B = d_B G` to Alice. Both of
them can then compute the point

.. MATH::

    d_A Q_B = d_A d_B G = d_B Q_A,

whose `x`-coordinate is their shared secret. An eavesdropper who wants to
recover the shared secret from `G`, `Q_A` and `Q_B` has to solve an instance
of the computational Diffie-Hellman problem in the group generated by `G`.

.. WARNING::

    This is a toy implementation for educational use only! Do not use
    this implementation, or any cryptographic features of Sage, in any
    setting where security is needed!

EXAMPLES:

A key exchange between Alice and Bob over the NIST curve P-256::

    sage: ECDH = key_exchange.EllipticCurveDiffieHellman.named_parameter_set('P-256')
    doctest:...: FutureWarning: SageMath's key exchange functionality is experimental and might change in the future.
                 See https://github.com/sagemath/sage/issues/41218 for details.
    sage: alice_sk = ECDH.secret_key()
    sage: alice_pk = ECDH.public_key(alice_sk)
    sage: bob_sk = ECDH.secret_key()
    sage: bob_pk = ECDH.public_key(bob_sk)
    sage: alice_shared_secret = ECDH.compute_shared_secret(alice_sk, bob_pk)
    sage: bob_shared_secret = ECDH.compute_shared_secret(bob_sk, alice_pk)
    sage: alice_shared_secret == bob_shared_secret
    True

AUTHORS:

- Jules Fressonnet (2026-11-15): initial version
"""

