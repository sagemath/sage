class EllipticCurveDiffieHellman(CommutativeKeyExchangeBase):
    r"""
    Elliptic curve Diffie-Hellman key exchange.

    A secret key is an integer `d`, the corresponding public key is the
    point `dG` where `G` is the base point, and the shared secret of two
    parties with secret keys `d_A` and `d_B` is the `x`-coordinate of the
    point `d_A d_B G`. This is the elliptic curve Diffie-Hellman primitive
    of Section 3.3.1 of [SEC1]_.

    INPUT:

    - ``E`` -- elliptic curve over a finite field

    - ``G`` -- base point of the key exchange; (coercible to) a point of
      ``E`` other than the point at infinity

    - ``order`` -- positive integer (default: ``None``); the order `n` of
      ``G``. If ``None``, the order is computed, which is expensive for
      curves of cryptographic size. If given, it is checked that the order
      of ``G`` is exactly ``order``, which requires the factorization of
      ``order``.

    .. NOTE::

        Standards such as [SEC1]_ require the order `n` of the base point
        to be a large prime. This is not required here, so that this class
        can also be used to experiment with attacks on weak parameters.

        If `n` is not prime, then the point `d_A d_B G` may be the point at
        infinity, which has no `x`-coordinate. To prevent this, the secret
        keys generated by :meth:`secret_key` are coprime to `n`. If `n` is
        prime, this is no restriction.

    REFERENCES:

    For more information, see Section 9.3 of [PP2010]_ and Chapter 3 of
    [SEC1]_.

    EXAMPLES:

    We reproduce the example of Section 9.3 of [PP2010]_, which uses the
    curve `y^2 = x^3 + 2x + 2` over `\GF{17}` and the base point `(5, 1)`
    of order `19`::

        sage: E = EllipticCurve(GF(17), [2, 2])
        sage: G = E(5, 1)
        sage: ECDH = key_exchange.EllipticCurveDiffieHellman(E, G)
        sage: ECDH
        EllipticCurveDiffieHellman with parameter set:
         (Elliptic Curve defined by y^2 = x^3 + 2*x + 2 over Finite Field of size 17,
          (5 : 1 : 1), 19)

    Alice chooses the secret key `3` and Bob chooses the secret key `10`.
    Their public keys are::

        sage: alice_pk = ECDH.public_key(3); alice_pk
        (10 : 6 : 1)
        sage: bob_pk = ECDH.public_key(10); bob_pk
        (7 : 11 : 1)

    Both of them arrive at the point `(13, 10)`, the `x`-coordinate of
    which is their shared secret::

        sage: ECDH.compute_shared_secret(3, bob_pk)
        13
        sage: ECDH.compute_shared_secret(10, alice_pk)
        13
        sage: 3 * 10 * G
        (13 : 10 : 1)

    The same parameter set is available under the name ``'toy'``, along
    with some parameter sets of cryptographic size, see
    :meth:`named_parameter_set`::

        sage: ECDH == key_exchange.EllipticCurveDiffieHellman.named_parameter_set('toy')
        True

    We check the test vector of Section 8.1 of [RFC5903]_ for the NIST
    curve P-256::

        sage: P256 = key_exchange.EllipticCurveDiffieHellman.named_parameter_set('P-256')
        sage: i = 0xC88F01F510D9AC3F70A292DAA2316DE544E9AAB8AFE84049C62A9C57862D1433
        sage: gix = 0xDAD0B65394221CF9B051E1FECA5787D098DFE637FC90B9EF945D0C3772581180
        sage: giy = 0x5271A0461CDB8252D61F1C456FA3E59AB1F45B33ACCF5F58389E0577B8990BB3
        sage: r = 0xC6EF9C5D78AE012A011164ACB397CE2088685D8F06BF9BE0B283AB46476BEE53
        sage: grx = 0xD12DFB5289C8D4F81208B70270398C342296970A0BCCB74C736FC7554494BF63
        sage: gry = 0x56FBF3CA366CC23E8157854C13C58D6AAC23F046ADA30F8353E74F33039872AB
        sage: girx = 0xD6840F6B42F6EDAFD13116E0E12565202FEF8E9ECE7DCE03812464D04B9442DE
        sage: P256.public_key(i).xy() == (gix, giy)
        True
        sage: P256.public_key(r).xy() == (grx, gry)
        True
        sage: P256.compute_shared_secret(i, (grx, gry)) == girx
        True
        sage: P256.compute_shared_secret(r, (gix, giy)) == girx
        True

    The elliptic curve can be defined over any finite field, for example
    over a binary field. If the order of the base point is not given, then
    it is computed::

        sage: K.<z> = GF(2^8)
        sage: E = EllipticCurve(K, [1, 0, 0, 0, z^3])
        sage: G = E(z^2 + z, z^3)
        sage: binary_ECDH = key_exchange.EllipticCurveDiffieHellman(E, G)
        sage: binary_ECDH.parameters()
        (Elliptic Curve defined by y^2 + x*y = x^3 + z^3 over Finite Field in z of size 2^8,
         (z^2 + z : z^3 : 1),
         31)
        sage: alice_sk, alice_pk, bob_sk, bob_pk, shared_secret = binary_ECDH.do_key_exchange()
        sage: shared_secret == (alice_sk * bob_sk * G).x()
        True
        sage: shared_secret.parent()
        Finite Field in z of size 2^8

    Since the parameters are not required to be cryptographically secure,
    this class can be used to experiment with attacks. Here the base point
    has order `2^{127}`, so an eavesdropper easily recovers the secret key
    of Alice from her public key with the Pohlig-Hellman algorithm,
    although the base field has `127` bits::

        sage: E = EllipticCurve(GF(2^127 - 1), [1, 0])
        sage: G = E.lift_x(3)
        sage: weak_ECDH = key_exchange.EllipticCurveDiffieHellman(E, G, order=2^127)
        sage: alice_sk = weak_ECDH.secret_key()
        sage: alice_pk = weak_ECDH.public_key(alice_sk)
        sage: alice_pk.log(G) == alice_sk
        True

    It is an error to use a curve which is not defined over a finite
    field, or the point at infinity as the base point::

        sage: E = EllipticCurve(QQ, [0, -1, 1, -10, -20])
        sage: key_exchange.EllipticCurveDiffieHellman(E, E(5, 5))
        Traceback (most recent call last):
        ...
        TypeError: E must be an elliptic curve over a finite field
        sage: E = EllipticCurve(GF(17), [2, 2])
        sage: key_exchange.EllipticCurveDiffieHellman(E, E(0))
        Traceback (most recent call last):
        ...
        ValueError: the base point must not be the point at infinity

    TESTS:

    The base point has to be a point of the curve::

        sage: key_exchange.EllipticCurveDiffieHellman(E, (5, 2))
        Traceback (most recent call last):
        ...
        TypeError: Coordinates [5, 2, 1] do not define a point on Elliptic Curve
        defined by y^2 = x^3 + 2*x + 2 over Finite Field of size 17

    A given order is checked rather than trusted::

        sage: G = E(5, 1)
        sage: key_exchange.EllipticCurveDiffieHellman(E, G, order=19) == ECDH
        True
        sage: for order in [-19, 0, 1, 18, 38]:
        ....:     try:
        ....:         key_exchange.EllipticCurveDiffieHellman(E, G, order=order)
        ....:     except ValueError as e:
        ....:         print(e)
        (5 : 1 : 1) does not have order -19
        (5 : 1 : 1) does not have order 0
        (5 : 1 : 1) does not have order 1
        (5 : 1 : 1) does not have order 18
        (5 : 1 : 1) does not have order 38
        sage: key_exchange.EllipticCurveDiffieHellman(E, G, order=19/2)
        Traceback (most recent call last):
        ...
        TypeError: no conversion of this rational to integer

    Instances with the same parameters are equal and have the same hash::

        sage: other_ECDH = key_exchange.EllipticCurveDiffieHellman(E, (5, 1))
        sage: other_ECDH == ECDH
        True
        sage: hash(other_ECDH) == hash(ECDH)
        True
        sage: other_ECDH == key_exchange.EllipticCurveDiffieHellman(E, (6, 3))
        False
    """

    def __init__(
        self,
        E: EllipticCurve_finite_field,
        G: EllipticCurvePoint_finite_field | tuple | list,
        order: Integer | int | None = None,
    ) -> None:
        r"""
        Initialize ``self``.

        TESTS::

            sage: ECDH = key_exchange.EllipticCurveDiffieHellman.named_parameter_set('toy')
            sage: TestSuite(ECDH).run()

        The key exchange also works if the order of the base point is not
        prime, here it is `28`::

            sage: E = EllipticCurve(GF(23), [1, 1])
            sage: ECDH = key_exchange.EllipticCurveDiffieHellman(E, E(0, 1))
            sage: TestSuite(ECDH).run()

        The smallest possible case is a base point of order `2`::

            sage: E = EllipticCurve(GF(7), [1, 0])
            sage: ECDH = key_exchange.EllipticCurveDiffieHellman(E, E(0, 0))
            sage: TestSuite(ECDH).run()
            sage: ECDH.do_key_exchange()
            (1, (0 : 0 : 1), 1, (0 : 0 : 1), 0)
        """
        if not isinstance(E, EllipticCurve_finite_field):
            raise TypeError('E must be an elliptic curve over a finite field')

        self._E = E
        self._G = E(G)

        if self._G.is_zero():
            raise ValueError('the base point must not be the point at infinity')

        if order is None:
            self._order = self._G.order()
        else:
            self._order = Integer(order)
            if not self._G.has_order(self._order):
                raise ValueError(f'{self._G} does not have order {self._order}')

    def secret_key(self) -> Integer:
        r"""
        Generate a random secret key.

        OUTPUT:

        A uniformly random integer `d` with `1 \leq d \leq n - 1` which is
        coprime to the order `n` of the base point. If `n` is prime, this
        is a uniformly random integer `d` with `1 \leq d \leq n - 1`, as in
        Section 3.2.1 of [SEC1]_.

        EXAMPLES::

            sage: ECDH = key_exchange.EllipticCurveDiffieHellman.named_parameter_set('toy')
            sage: 1 <= ECDH.secret_key() <= 18
            True

        TESTS:

        If the order of the base point is not prime, then the secret keys
        are coprime to it::

            sage: E = EllipticCurve(GF(23), [1, 1])
            sage: ECDH = key_exchange.EllipticCurveDiffieHellman(E, E(0, 1))
            sage: keys = [ECDH.secret_key() for _ in range(50)]
            sage: all(1 <= d <= 27 and gcd(d, 28) == 1 for d in keys)
            True
        """
        while True:
            d = ZZ.random_element(1, self._order)
            if d.gcd(self._order).is_one():
                return d

    def public_key(self, secret_key) -> EllipticCurvePoint_finite_field:
        r"""
        Return the public key corresponding to the given secret key.

        INPUT:

        - ``secret_key`` -- integer; the secret key `d`

        OUTPUT: the point `dG` where `G` is the base point

        EXAMPLES::

            sage: ECDH = key_exchange.EllipticCurveDiffieHellman.named_parameter_set('toy')
            sage: ECDH.public_key(3)
            (10 : 6 : 1)

        TESTS::

            sage: ECDH.public_key(3/2)
            Traceback (most recent call last):
            ...
            TypeError: no conversion of this rational to integer
        """
        return Integer(secret_key) * self._G

    def compute_shared_secret(self, secret_key, public_key) -> FiniteRingElement:
        r"""
        Compute the shared secret from the secret key of one party and
        the public key of the other party.

        The public key is first validated as in Section 3.2.2.1 of
        [SEC1]_: it has to be a point of the elliptic curve other than the
        point at infinity, and its order has to divide the order of the
        base point.

        INPUT:

        - ``secret_key`` -- integer; the secret key `d` of one party

        - ``public_key`` -- the public key `Q` of the other party;
          (coercible to) a point of the elliptic curve

        OUTPUT:

        The `x`-coordinate of the point `dQ`, an element of the base field
        of the elliptic curve

        EXAMPLES::

            sage: ECDH = key_exchange.EllipticCurveDiffieHellman.named_parameter_set('toy')
            sage: ECDH.compute_shared_secret(3, ECDH.public_key(10))
            13
            sage: ECDH.compute_shared_secret(10, ECDH.public_key(3))
            13

        The public key can also be given by its coordinates::

            sage: ECDH.compute_shared_secret(3, (7, 11))
            13

        It is an error to use a public key which is not a point of the
        elliptic curve. Accepting such a public key would allow an invalid
        curve attack::

            sage: ECDH.compute_shared_secret(3, (7, 12))
            Traceback (most recent call last):
            ...
            TypeError: Coordinates [7, 12, 1] do not define a point on Elliptic Curve
            defined by y^2 = x^3 + 2*x + 2 over Finite Field of size 17

        It is also an error to use the point at infinity as the public
        key, or a public key whose order does not divide the order of the
        base point. Accepting such public keys would allow a small subgroup
        attack. Here the base point has order `7` on a curve with `28`
        points, and the rejected public key has order `2`::

            sage: E = EllipticCurve(GF(23), [1, 1])
            sage: ECDH = key_exchange.EllipticCurveDiffieHellman(E, E(13, 16))
            sage: ECDH.compute_shared_secret(3, E(0))
            Traceback (most recent call last):
            ...
            ValueError: the public key must not be the point at infinity
            sage: ECDH.compute_shared_secret(3, E(4, 0))
            Traceback (most recent call last):
            ...
            ValueError: the order of the public key must divide
            the order of the base point

        TESTS:

        If the order of the base point is not prime, then the shared
        secret is not defined for all secret keys, but it is for the ones
        generated by :meth:`secret_key`::

            sage: ECDH = key_exchange.EllipticCurveDiffieHellman(E, E(0, 1))
            sage: ECDH.compute_shared_secret(14, ECDH.public_key(2))
            Traceback (most recent call last):
            ...
            ValueError: the shared secret is not defined because
            secret_key * public_key is the point at infinity
            sage: ECDH.compute_shared_secret(3, ECDH.public_key(5))
            9
        """
        Q = self._E(public_key)

        if Q.is_zero():
            raise ValueError('the public key must not be the point at infinity')

        if not (self._order * Q).is_zero():
            raise ValueError(
                'the order of the public key must divide the order of the base point'
            )

        P = Integer(secret_key) * Q

        if P.is_zero():
            raise ValueError(
                'the shared secret is not defined because '
                'secret_key * public_key is the point at infinity'
            )

        return P.x()

    def parameters(
        self,
    ) -> tuple[EllipticCurve_finite_field, EllipticCurvePoint_finite_field, Integer]:
        r"""
        Return the public parameters of this key exchange.

        OUTPUT: a tuple of

        - the elliptic curve `E`

        - the base point `G`

        - the order `n` of `G`

        EXAMPLES::

            sage: ECDH = key_exchange.EllipticCurveDiffieHellman.named_parameter_set('toy')
            sage: ECDH.parameters()
            (Elliptic Curve defined by y^2 = x^3 + 2*x + 2 over Finite Field of size 17,
             (5 : 1 : 1),
             19)
        """
        return (self._E, self._G, self._order)

    @classmethod
    def named_parameter_set(cls, name: str) -> Self:
        r"""
        Return the key exchange corresponding to a named parameter set.

        INPUT:

        - ``name`` -- string; one of the following:

          - ``'toy'`` -- the curve `y^2 = x^3 + 2x + 2` over `\GF{17}` with
            a base point of order `19`, this toy example is from
            Section 9.3 of [PP2010]_
          - ``'P-256'`` -- the NIST curve P-256, also known as secp256r1
            and prime256v1
          - ``'P-384'`` -- the NIST curve P-384, also known as secp384r1
          - ``'P-521'`` -- the NIST curve P-521, also known as secp521r1
          - ``'secp256k1'`` -- the curve secp256k1 used by Bitcoin

          The parameters of all these curves but the first one are taken
          from [SEC2]_.

        EXAMPLES::

            sage: ECDH = key_exchange.EllipticCurveDiffieHellman
            sage: toy = ECDH.named_parameter_set('toy')
            sage: toy
            ecdh-toy
            sage: toy.parameters()
            (Elliptic Curve defined by y^2 = x^3 + 2*x + 2 over Finite Field of size 17,
             (5 : 1 : 1),
             19)

        The order of the base point of the curve secp256k1 is a prime
        number of `256` bits::

            sage: secp256k1 = ECDH.named_parameter_set('secp256k1')
            sage: secp256k1
            ecdh-secp256k1
            sage: E, G, n = secp256k1.parameters()
            sage: E
            Elliptic Curve defined by y^2 = x^3 + 7 over Finite Field of size
            115792089237316195423570985008687907853269984665640564039457584007908834671663
            sage: n.is_prime(), n.nbits()
            (True, 256)

        It is an error to ask for an unknown parameter set::

            sage: ECDH.named_parameter_set('P-123')
            Traceback (most recent call last):
            ...
            ValueError: Unknown parameter set name "P-123" for <class
            'sage.crypto.public_key.key_exchange.elliptic_curve_diffie_hellman.EllipticCurveDiffieHellman'>

        TESTS:

        For each of the curves from [SEC2]_, the order `n` of the base
        point is prime and the cofactor is `1`. The latter follows from the
        Hasse bound because `2n` is larger than `(\sqrt{p} + 1)^2`::

            sage: for name in ['P-256', 'P-384', 'P-521', 'secp256k1']:  # long time
            ....:     E, G, n = ECDH.named_parameter_set(name).parameters()
            ....:     p = E.base_field().cardinality()
            ....:     print(name, p.nbits(), n.is_prime(), 2*n > (p.isqrt() + 2)^2)
            P-256 256 True True
            P-384 384 True True
            P-521 521 True True
            secp256k1 256 True True

        A key exchange over each of them::

            sage: for name in ['P-256', 'P-384', 'P-521', 'secp256k1']:  # long time
            ....:     TestSuite(ECDH.named_parameter_set(name)).run()
        """
        if name not in _NAMED_PARAMETER_SETS:
            return super().named_parameter_set(name)

        p, a, b, x, y, n = _NAMED_PARAMETER_SETS[name]
        E = EllipticCurve(GF(p), [a, b])
        ecdh = cls(E, E(x, y), order=n)
        ecdh.rename(f'ecdh-{name}')
        return ecdh
