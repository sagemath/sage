r"""
Seed data for published Hadamard matrices

The twelve records below are the matrices of Alpöge, Voinov and Reynolds-Haertle
analysed in [EKLO2026]_, Section 3, Tables 1 and 2. They are decoded from the
original public sign payload and header table. No shell decoder or network
access is needed to use them.
The discovery method of these particular seeds is not assumed.

The complete 23828-sign payload has SHA-256
``5b5fe8fa42f0d6a8b4e4c9926726d82a6aab8e1070c1ae4d1b430c1277e58db4``.
The decoder text has SHA-256
``30d552fa26eab955cf73d7c762b34e23bea5a3ba70e384518cf718b040fd9f0a``.

For Spence and Goethals-Seidel, each record consists of four sign sequences.
For the larger borders, each record is a tuple
``(factors, border, top_pair_repetitions, data)``. The cyclic factor orders
specify a development group in lexicographic coordinate order, with the last
coordinate varying fastest. The six strings in ``data`` contain the four core
seeds concatenated, the compressed top border, and the four compressed left
borders. Each top-border row starts with ``border`` corner signs; its remaining
signs are expanded by repeating each pair ``top_pair_repetitions`` times, then
repeating each sign by the last cyclic factor order. Each compressed left-border
row is repeated by that same factor order. The strings retain their published
order, so concatenating the records by increasing matrix order recovers the
original payload.

The records in ``EKLO_GOETHALS_SEIDEL_DATA`` encode the four unbordered
Goethals--Seidel constructions of [EKLO2026]_, Section 4, at orders 3732,
4492, 5020 and 5932. Each record contains a multiplier subgroup and four
lists of representatives whose orbits specify the negative entries of the
circulant seeds. Source URLs and extraction conventions are recorded below.

``EKLO_BORDERED_DATA`` stores the generalized bordered construction of order
5788 from the same paper. Its record specifies the cyclic factors, border
size, coset size, and compressed sign data, with conventions recorded below.

TESTS::

    sage: from sage.combinat.matrices.hadamard_matrix_data import (
    ....:     ALPOGE_SPENCE_DATA, ALPOGE_GOETHALS_SEIDEL_DATA, ALPOGE_BORDERED_DATA)
    sage: sorted(ALPOGE_SPENCE_DATA)
    [668, 716, 1676, 1772]
    sage: sorted(ALPOGE_GOETHALS_SEIDEL_DATA)
    [892, 1132, 1244, 1948, 1964]
    sage: sorted(ALPOGE_BORDERED_DATA)
    [1388, 1436, 1916]
    sage: from sage.combinat.matrices.hadamard_matrix_data import (
    ....:     EKLO_GOETHALS_SEIDEL_DATA)
    sage: [(n, len(data[0]))
    ....:  for n, data in sorted(EKLO_GOETHALS_SEIDEL_DATA.items())]
    [(3732, 31), (4492, 33), (5020, 50), (5932, 39)]
    sage: from sage.combinat.matrices.hadamard_matrix_data import (
    ....:     EKLO_BORDERED_DATA)
    sage: sorted(EKLO_BORDERED_DATA)
    [5788]
"""

