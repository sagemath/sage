r"""
Hyperoctahedral species

This module provides the internal infrastructure for *polynomial
`r`-species* in the sense of Henderson [Henderson2004]_, i.e. functors
on the category `\mathbf B_r` of finite sets with a free action of the
cyclic group `C_r` of order `r`.  The case `r = 2` is the
*hyperoctahedral* case.

The present module only contains the combinatorial model of the
canonical permutation representation of the wreath product

.. MATH::

    W(r,n) = C_r \wr S_n \leq S_{rn},

together with the computation of the cycle type of its elements.  The
species themselves are built on top of this in
:mod:`sage.rings.species_hyperoctahedral`.

The group `W(r,n)` is realized as a permutation group on the `r n`
points `1, \ldots, r n`, split into `n` *consecutive* blocks of size
`r`.  This block system is the data that distinguishes `W(r,n)`-sets
from ordinary `S_{rn}`-sets; it is therefore available at all times
through :func:`_wreath_blocks`.

Following Henderson, conjugacy classes of `W(r,n)` are indexed by
collections `(a_i(\zeta))_{i \geq 1, \zeta \in \mu_r}` of
nonnegative integers with

.. MATH::

    \sum_{i \geq 1} \sum_{\zeta \in \mu_r} i a_i(\zeta) = n,

where `a_i(\zeta)` counts the cycles of length `i` and type `\zeta`.
We never represent `\zeta` by an actual root of unity: instead the
`r` possible types are the labels `0, 1, \ldots, r-1` and the type of a
cycle is the sum, modulo `r`, of the sign labels occurring in it.
:func:`_wreath_cycle_type` returns this data as an `r`-tuple of
(ordinary) partitions of `n`.

The conjugacy classes of *subgroups* of `W(r,n)`, which are needed to
classify molecular `r`-species, are available directly from the
permutation group returned by :func:`_wreath_group`, via
:meth:`~sage.groups.perm_gps.permgroup.PermutationGroup_generic.conjugacy_classes_subgroups`::

    sage: from sage.groups.perm_gps.hyperoctahedral_group import _wreath_group
    sage: G = _wreath_group(2, 2)
    sage: len(G.conjugacy_classes_subgroups())
    8

.. NOTE::

    The groups in :mod:`sage.combinat.colored_permutations` realize the
    same abstract wreath products, but the permutation realization used
    by
    :meth:`~sage.combinat.colored_permutations.ColoredPermutations.as_permutation_group`
    labels the `r n` points differently and does not expose a block
    system.  The consecutive-block model used here is the one required
    for `r`-species, so we build the permutation group directly.

REFERENCES:

.. [Henderson2004] Anthony Henderson.
   *Representations of wreath products on cohomology of De Concini-Procesi
   compactifications*.
   International Mathematics Research Notices 2004, no. 20, 981-1021.

AUTHORS:

- Martin Rubey (2026): initial version
"""


