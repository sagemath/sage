from typing import assert_type

from sage.rings.integer import Integer
from sage.structure.factorization import Factorization

n = Integer(12)

assert_type(n.binomial(5), Integer)
assert_type(n.bit_length(), int)
assert_type(n.ceil(), Integer)
assert_type(n.denominator(), Integer)
assert_type(n.divides(24), bool)
assert_type(n.exact_log(2), Integer)
assert_type(n.factor(), Factorization)
assert_type(n.factorial(), Integer)
assert_type(n.floor(), Integer)
assert_type(n.inverse_mod(5), Integer)
assert_type(n.is_irreducible(), bool)
assert_type(n.is_one(), bool)
assert_type(n.is_perfect_power(), bool)
assert_type(n.is_prime(), bool)
assert_type(n.is_prime_power(), bool)
assert_type(n.is_prime_power(get_data=True), tuple[Integer, Integer])
assert_type(n.is_pseudoprime(), bool)
assert_type(n.is_pseudoprime_power(get_data=True), tuple[Integer, Integer])
assert_type(n.is_squarefree(), bool)
assert_type(n.is_unit(), bool)
assert_type(n.isqrt(), Integer)
assert_type(n.jacobi(5), int)
assert_type(n.kronecker(5), int)
assert_type(n.nbits(), int)
assert_type(n.ndigits(), Integer)
assert_type(n.next_prime(), Integer)
assert_type(n.next_probable_prime(), Integer)
assert_type(n.numerator(), Integer)
assert_type(n.odd_part(), Integer)
assert_type(n.ordinal_str(), str)
assert_type(n.perfect_power(), tuple[Integer, Integer])
assert_type(n.popcount(), Integer)
assert_type(n.powermod(3, 7), Integer)
assert_type(n.previous_prime(), Integer)
assert_type(n.prime_to_m_part(3), Integer)
assert_type(n.quo_rem(5), tuple[Integer, Integer])
assert_type(n.real(), Integer)
assert_type(n.round(), Integer)
assert_type(n.sign(), Integer)
assert_type(n.sqrtrem(), tuple[Integer, Integer])
assert_type(n.str(), str)
assert_type(n.support(), list[Integer])
assert_type(n.test_bit(1), int)
assert_type(n.to_bytes(), bytes)
assert_type(n.trailing_zero_bits(), int)
assert_type(n.trunc(), Integer)
assert_type(n.valuation(2), Integer)
assert_type(n.xgcd(5), tuple[Integer, Integer, Integer])
